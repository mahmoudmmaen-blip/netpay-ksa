  final q = question.toLowerCase();

  // نهاية الخدمة والفصل
  if (q.contains('نهاية') ||
      q.contains('مكافأ') ||
      q.contains('مكافاة') ||
      q.contains('استقالة') ||
      q.contains('فصل') ||
      q.contains('وهمشوني') ||
      q.contains('همشوني') ||
      q.contains('طردوني') ||
      q.contains('شيلوني') ||
      q.contains('ونهاية') ||
      q.contains('مستحقاتي') ||
      q.contains('حقوقي')) {
    return '''
