= 10,000 × ثلثان × 6 = 40,000 ريال

⚠️ إذا كان الفصل تعسفياً (بدون سبب مشروع) يحق لك تعويض إضافي.

جرّب حاسبة نهاية الخدمة في التطبيق لحساب مستحقاتك بدقة.
تنبيه: هذه معلومات عامة وليست استشارة قانونية ملزمة.
''';
  }

  // GOSI والتأمينات
  if (q.contains('gosi') ||
      q.contains('جوسي') ||
      q.contains('تأمين') ||
      q.contains('تامين') ||
      q.contains('تأمينات') ||
      q.contains('اشتراك')) {
    return '''
التأمينات الاجتماعية (GOSI) — السعودية:

📊 نسب 2026 (مرحلة انتقالية):
- خصم الموظف: 9.75%
- اشتراك صاحب العمل: 11.75%

📅 نسب 2027:
- موظف: 10% | صاحب عمل: 12.25%

👤 لغير السعوديين:
تأمين إصابات مهنية فقط: 2% على صاحب العمل (لا خصم من الراتب)

استخدم حاسبة NetGulf على الشاشة الرئيسية لحساب صافي راتبك بدقة.
تنبيه: رد تجريبي — راجع المؤسسة العامة للتأمينات الاجتماعية.
''';
  }

  // الإجازات
  if (q.contains('إجاز') ||
      q.contains('اجاز') ||
      q.contains('إجازة') ||
      q.contains('مرضية') ||
      q.contains('سنوية') ||
      q.contains('أمومة') ||
      q.contains('امومة')) {
    if (q.contains('مرضية') || q.contains('مريض')) {
      return '''
الإجازة المرضية — نظام العمل السعودي (المادة 117):

- أول 30 يوم: أجر كامل (100%)
- 31 إلى 90 يوم: ثلاثة أرباع الأجر (75%)
- 91 إلى 120 يوم: بدون أجر

📋 الشروط: تقديم شهادة طبية معتمدة — تُحسب تراكمياً في السنة.

تنبيه: هذه معلومات عامة وليست استشارة قانونية ملزمة.
''';
    }
    return '''
الإجازات السنوية — نظام العمل السعودي (المادة 109):

- أقل من 5 سنوات خدمة: 21 يوم عمل
- 5 سنوات فأكثر: 30 يوم عمل

📋 قواعد مهمة:
- الأجر يُحسب بالراتب الأساسي + البدلات المنتظمة
- لا يجوز تأجيل الإجازة أكثر من سنة بدون موافقتك
- إذا انتهت الخدمة دون أخذ الإجازة تُصرف نقداً

في الإمارات: 30 يوماً سنوياً بعد سنة خدمة كاملة.
تنبيه: هذه معلومات عامة وليست استشارة قانونية ملزمة.
''';
  }

  // الإمارات
  if (q.contains('إمارات') ||
      q.contains('امارات') ||
      q.contains('دبي') ||
      q.contains('أبوظبي') ||
      q.contains('ابوظبي') ||
      q.contains('gpssa') ||
      q.contains('dews')) {
    return '''
نظام العمل الإماراتي (القانون الاتحادي 33 لسنة 2021):

💰 مكافأة نهاية الخدمة:
- 21 يوم أجر أساسي عن كل سنة (أول 5 سنوات)
- 30 يوم عن كل سنة إضافية بعد 5 سنوات
- الحد الأقصى: أجر سنتين كاملتين
- لا فرق بين استقالة وفصل (تعديل 2022)

📊 GPSSA للمواطنين الإماراتيين:
- موظف: 5% | صاحب عمل: 12.5% | حكومة: 2.5%

📅 الإجازة السنوية: 30 يوم بعد سنة كاملة

افتح حاسبة الإمارات من الشاشة الرئيسية للتفاصيل.
تنبيه: رد تجريبي — راجع وزارة الموارد البشرية والتوطين.
''';
  }

  // إشعار وفترة التجربة
  if (q.contains('إشعار') ||
      q.contains('اشعار') ||
      q.contains('مهلة') ||
      q.contains('تجربة') ||
      q.contains('فترة التجربة')) {
    return '''
إشعار إنهاء العقد — نظام العمل السعودي:

📋 عقد غير محدد المدة: 60 يوم إشعار مسبق كحد أدنى
📋 عقد محدد المدة: ينتهي بانتهاء مدته

⏱️ فترة التجربة:
- الحد الأقصى: 90 يوم (قابلة للتمديد مرة واحدة فقط)
- خلالها: يمكن لأي طرف الإنهاء بإشعار 30 يوم

💡 إذا لم يُعطَ الإشعار: يحق للطرف المتضرر مطالبة الآخر بأجر مدة الإشعار كاملاً.

تنبيه: هذه معلومات عامة وليست استشارة قانونية ملزمة.
''';
  }

  // رد عام
  return '''
شكراً لسؤالك حول: «$question»

أنا المساعد القانوني في NetGulf (وضع تجريبي). يمكنني مساعدتك في:

🇸🇦 قانون العمل السعودي:
- حساب مكافأة نهاية الخدمة (المادتان 84 و85)
- اشتراكات GOSI والتأمينات الاجتماعية
- الإجازات السنوية والمرضية وإجازة الأمومة
- حقوق الفصل والتعسف وإشعار الإنهاء

🇦🇪 قانون العمل الإماراتي:
- مكافأة نهاية الخدمة (DEWS/GPSSA)
- الإجازات والحقوق العمالية

💬 اسألني بأي لغة أو لهجة — حتى لو فيه أخطاء إملائية، سأفهمك!

عند تفعيل الذكاء الاصطناعي الكامل ستصلك إجابات أدق مع ذكر المواد القانونية.
تنبيه: هذه معلومات عامة وليست استشارة قانونية ملزمة.
''';
}
