- 2 إلى 5 سنوات → ثلث الأجر × عدد السنوات (استقالة) / نصف الأجر (فصل)
- 5 إلى 10 سنوات → ثلثا الأجر × عدد السنوات (استقالة) / الأجر كاملاً (فصل)
- 10 سنوات فأكثر → الأجر كاملاً × عدد السنوات (استقالة أو فصل)

